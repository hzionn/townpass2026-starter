#!/usr/bin/env node
/**
 * Regenerates server/src/data/healthcheckSites.ts from the official open dataset.
 *
 *   node scripts/import-healthcheck-sites.mjs <downloaded-csv> <metadata-json>
 *
 * Download both files first (URLs below) into an empty directory of their own.
 * The CSV is Big5-encoded. Only institution name and address are kept: the phone
 * columns are not needed by the form, so they stay out of this repo.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const DATASET_ID = '9a1aefde-2e4a-467c-9ec4-256e33ad6df0';
const RESOURCE_ID = 'ca9b88ff-a881-4ca3-a3a4-b26747f3e3e7';
const LANDING_PAGE = `https://data.taipei/dataset/detail?id=${DATASET_ID}`;
const DOWNLOAD_URL = `https://data.taipei/api/dataset/${DATASET_ID}/resource/${RESOURCE_ID}/download`;
const OUTPUT = resolve(import.meta.dirname, '../server/src/data/healthcheckSites.ts');
const DISTRICT_ORDER = ['中正區', '大同區', '中山區', '松山區', '大安區', '萬華區', '信義區', '士林區', '北投區', '內湖區', '南港區', '文山區'];

const [csvPath, metadataPath] = process.argv.slice(2);
if (!csvPath || !metadataPath) {
  console.error('usage: import-healthcheck-sites.mjs <downloaded-csv> <metadata-json>');
  console.error(`  CSV:      ${DOWNLOAD_URL}`);
  console.error(`  Metadata: https://data.taipei/api/frontstage/tpeod/dataset.view?id=${DATASET_ID}`);
  process.exit(2);
}

/** Minimal RFC 4180 parser: quoted fields, doubled quotes, CRLF. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = '';
  let quoted = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i += 1;
      } else if (ch === '"') {
        quoted = false;
      } else {
        field += ch;
      }
    } else if (ch === '"') {
      quoted = true;
    } else if (ch === ',') {
      row.push(field);
      field = '';
    } else if (ch === '\n') {
      row.push(field.replace(/\r$/, ''));
      rows.push(row);
      row = [];
      field = '';
    } else {
      field += ch;
    }
  }
  if (field !== '' || row.length > 0) {
    row.push(field.replace(/\r$/, ''));
    rows.push(row);
  }
  return rows;
}

const bytes = readFileSync(csvPath);
const rows = parseCsv(new TextDecoder('big5').decode(bytes)).filter((r) => r.some((cell) => cell.trim() !== ''));
const header = rows[0].map((h) => h.replace(/^﻿/, '').trim());
const nameColumn = header.indexOf('醫事機構名稱');
const addressColumn = header.indexOf('顯示用地址');
if (nameColumn < 0 || addressColumn < 0) {
  throw new Error(`Unexpected CSV columns: ${header.join(', ')}`);
}

const metadata = JSON.parse(readFileSync(metadataPath, 'utf8'));
const dataset = metadata.payload;
if (!dataset?.title || !dataset.license_name || !dataset.changed) throw new Error('Unexpected metadata shape');

const seen = new Set();
const sites = rows.slice(1).map((row) => {
  const name = row[nameColumn].trim();
  const address = row[addressColumn].trim();
  const district = /^臺北市(..區)/.exec(address)?.[1];
  if (!name || !address || !DISTRICT_ORDER.includes(district)) {
    throw new Error(`Row ${JSON.stringify([name, address])} has no usable name, address or Taipei district`);
  }
  // The dataset has no stable ID, so derive one that survives re-imports and reordering.
  const id = `site-${createHash('sha256').update(`${name}|${address}`).digest('hex').slice(0, 12)}`;
  if (seen.has(id)) throw new Error(`Duplicate row: ${name}`);
  seen.add(id);
  return { id, name, district, address };
});

sites.sort(
  (a, b) => DISTRICT_ORDER.indexOf(a.district) - DISTRICT_ORDER.indexOf(b.district) || a.name.localeCompare(b.name, 'zh-Hant'),
);

const source = {
  datasetName: dataset.title,
  provider: dataset.maintainer_organization_name,
  landingPage: LANDING_PAGE,
  downloadUrl: DOWNLOAD_URL,
  licence: dataset.license_name,
  lastChanged: dataset.changed.slice(0, 10),
  retrievedAt: new Date().toISOString().slice(0, 10),
  csvSha256: createHash('sha256').update(bytes).digest('hex'),
};

const output = `// Generated by scripts/import-healthcheck-sites.mjs. Do not edit by hand.
// Real institutions from open data. The booking itself remains simulated (spec §6.1).

export interface HealthcheckSite {
  id: string;
  name: string;
  district: string;
  address: string;
}

export const HEALTHCHECK_SITES_SOURCE = ${JSON.stringify(source, null, 2)} as const;

export const HEALTHCHECK_SITES: readonly HealthcheckSite[] = ${JSON.stringify(sites, null, 2)};
`;
writeFileSync(OUTPUT, output);
console.log(`Wrote ${sites.length} sites to ${OUTPUT}`);
